    if R.get("tapp_description"):
        # Per-TAPP scope boilerplate as an editable JSON Schema default (the base tappDefinition
        # declares schema:description as a plain string; this layer only pre-fills it). Lab-specific
        # instances of the TAPP may amend or extend the text.
        tapp_props["schema:description"] = {
            "type": "string", "default": R["tapp_description"],
            "description": ("Human-readable statement of this protocol's scope, pre-filled as editable "
                            "boilerplate; lab-specific instances may amend or extend it.")}
    enum_props = CFG["enum_props"]
    mode_names = R.get("mode_names") or []
    for b in R["tapp_prop"]:
        key = "ada:" + b["name"] + ("Default" if b["A"] == "Editable" else "")
        if b["name"] == "analyticalMode":
            key = "ada:analyticalMode"  # never carries a …Default suffix
            # always a LIST of strings; options are the mode-column headers
            items = {"type": "string"}
            if mode_names:
                items["enum"] = list(mode_names)
            tapp_props[key] = {"description": b["desc"], "type": "array", "items": items}
        elif b["name"] in enum_props:
            tapp_props[key] = {"description": b["desc"], "type": "string",
                               "enum": with_sentinel(enum_props[b["name"]])}
        elif b["jtype"] in ("number", "integer"):
            tapp_props[key] = {"description": b["desc"], "anyOf": [{"type": "number"}, {"type": "string"}]}
        else:
            tapp_props[key] = {"description": b["desc"], "type": "string"}
        if b["cov"] > 0:
            basic_required.append(key)
    if acols:
        ac_refs = [{"$ref": "../../../../BaseSchema/tappDefinition/schema.yaml#/$defs/AnalyteIdentifierColumn"}] + \
                  [{"$ref": "../../../../registry/analyteColumns/schema.yaml#/$defs/" + c} for c in acols]
        ac_contains = [{"contains": {"$ref": "../../../../registry/analyteColumns/schema.yaml#/$defs/" + c},
                        "minContains": 0, "maxContains": 1} for c in acols]
        tapp_props["ada:analyteTemplate"] = {"type": "object", "properties": {
            "ada:analyteColumns": {"type": "array", "items": {"anyOf": ac_refs}, "allOf": ac_contains}}}
    sap_refs = [{"$ref": "../../../../registry/parameterTemplates/schema.yaml#/$defs/" + n} for n in pt_keys] + \
               [{"$ref": "../../../../registry/parameterValues/schema.yaml#/$defs/" + n} for n in mv_keys]
    sap_contains = [{"contains": {"$ref": "../../../../registry/parameterTemplates/schema.yaml#/$defs/" + n},
                     "minContains": 0, "maxContains": 1} for n in pt_keys] + \
                   [{"contains": {"$ref": "../../../../registry/parameterValues/schema.yaml#/$defs/" + n},
                     "minContains": 0, "maxContains": 1} for n in mv_keys]
    if sap_refs:  # omit the overlay constraint when the technique has no Advanced params
        tapp_props["schema:additionalProperty"] = {
            "type": "array",
            "description": ("Method-level Advanced-protocol parameters. Editable parameters are "
                            "schema:PropertyValueSpecification entries (…Default name; the per-dataset value "
                            "lives in the detail block); read-only parameters are schema:PropertyValue entries "
                            "carrying the fixed protocol value in schema:value."),
            "items": {"anyOf": sap_refs}, "allOf": sap_contains}
    tapp_schema = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": CFG["title"], "description": CFG["description"],
        "allOf": [{"$ref": "../../../../BaseSchema/tappDefinition/schema.yaml"},
                  {"type": "object", "properties": tapp_props, "required": basic_required}]}
    write(os.path.join(TAPP_DIR, "schema.yaml"), dump_yaml(tapp_schema))

    # ---- detail schema ----
    req = ["ada:componentType"]
    block1 = {
        "ada:componentType": {"anyOf": [{"const": c} for c in CFG["component_types"]]},
        "schema:measurementTechnique": {"type": "array", "items": {"type": "object",
            "description": f"@id reference to a registered {TAPP} TAPP definition.",
            "properties": {"@id": {"type": "string", "format": "uri"}}, "required": ["@id"]}}}
    for b in R["detail_req"]:
        key = "ada:" + b["name"]
        if b["jtype"] in ("number", "integer"):
            # accept a typed number OR a qualified string (publication fidelity, e.g. "~380 slices")
            block1[key] = {"description": b["desc"], "anyOf": [{"type": b["jtype"]}, {"type": "string"}]}
        elif b["jtype"] == "boolean":
            block1[key] = {"description": b["desc"], "type": "boolean"}
        else:
            block1[key] = {"description": b["desc"], "type": "string"}
        if not b["multivol_only"]:
            req.append(key)
    pv_branches = [{"$ref": "../../../../registry/parameterValues/schema.yaml#/$defs/" + n} for n in pv_keys]
    catchall = {"type": "object",
        "description": f"Catch-all for additional schema:PropertyValue entries beyond the {TAPP}-derived catalog.",
        "properties": {"@type": {"type": "array", "items": {"type": "string"},
                                 "contains": {"const": "schema:PropertyValue"}},
                       "schema:propertyID": {"type": "object", "required": ["@id"],
                                             "properties": {"@id": {"type": "string", "not": {"enum": pv_ids}}}}},
        "required": ["@type", "schema:propertyID"]}
    detail = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": CFG["detail_title"], "description": CFG["detail_description"],
        "allOf": [{"type": "object", "properties": block1, "required": req},
                  {"type": "object", "properties": {"schema:additionalProperty": {
                      "type": "array", "description": "Per-dataset schema:PropertyValue entries. All optional.",
                      "items": {"anyOf": pv_branches + [catchall]}}}}]}
    write(os.path.join(DETAIL_DIR, "schema.yaml"), dump_yaml(detail))

    base_tags = ["ada", "astromat", "tapp", CFG["prefix"].lower(), "technique-protocol"]
    write_bblock_if_missing(TAPP_DIR, CFG["title"], CFG["description"], base_tags)
    write_bblock_if_missing(DETAIL_DIR, CFG["detail_title"], CFG["detail_description"],
                            ["ada", "astromat", "instrument", CFG["prefix"].lower()])

    os.makedirs(os.path.join(ROOT, "docs", "new_tapps202606"), exist_ok=True)
    json.dump({"tapp_props": list(tapp_props.keys()), "pt_keys": pt_keys, "pv_keys": pv_keys,
               "analyte_cols": acols, "detail_req": [b["name"] for b in R["detail_req"]],
               "detail_req_multivol": [b["name"] for b in R["detail_req"] if b["multivol_only"]],
               "component_types": CFG["component_types"], "basic_required": basic_required,
               "basic_props": [{"key": "ada:" + b["name"] + ("Default" if b["A"] == "Editable" else ""),
                                "item": b["item"], "jtype": b["jtype"], "cov": b["cov"],
                                "required": b["cov"] > 0} for b in R["tapp_prop"]]},
              open(os.path.join(ROOT, "docs", "new_tapps202606", CFG["prefix"] + "_gen_index.json"), "w"), indent=1)
    print(f"DONE {TAPP}: tapp_prop={len(R['tapp_prop'])} method_param={len(pt_keys)} "
          f"detail_req={len(R['detail_req'])} detail_addl={len(pv_keys)} analyteCols={len(acols)} vocab={len(R['vocab'])}")


