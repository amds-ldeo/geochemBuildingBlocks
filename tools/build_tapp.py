def configure(tapp_name):
    global CFG, TAPP, PARAM_BASE, VOCAB_BASE, TAPP_DIR, DETAIL_DIR, XLSX
    if tapp_name not in TAPP_CONFIGS:
        raise SystemExit(f"Unknown TAPP {tapp_name!r}. Known: {sorted(TAPP_CONFIGS)}")
    CFG = TAPP_CONFIGS[tapp_name]
    TAPP = tapp_name
    PARAM_BASE = "ada:parameter/" + TAPP
    VOCAB_BASE = "ada:vocab/" + TAPP
    tech = TECH_DIR[TAPP]
    TAPP_DIR = os.path.join(TPROF, tech, "tapp")
    DETAIL_DIR = os.path.join(TPROF, tech, "detail")
    XLSX = os.path.join(ROOT, *CFG["xlsx"].split("/"))


# ---------- small helpers ----------
def norm(v):
    return " ".join(str(v).split()) if v is not None else ""


def camel(s):
    """camelCase a workbook item name into a CURIE local name.

    A CURIE local name must start with a letter ([A-Za-z][A-Za-z0-9]*), so an item whose name
    leads with a number — "3D Image Registration" — cannot simply be lower-camelled: the naive
    `3dImageRegistration` is rejected by the schema-path parser. Leading numeric tokens are moved
    to the end instead, giving `imageRegistration3D`, which is the convention already hand-authored
    in the sidecars for exactly these rows.
    """
    s = re.sub(r"\(.*?\)", "", s)
    s = re.sub(r"[^A-Za-z0-9 ]", " ", s).strip()
    parts = s.split()
    if not parts:
        return "x"
    trailing = []
    while len(parts) > 1 and parts[0][0].isdigit():
        trailing.append(parts.pop(0).upper())
    out = parts[0].lower() + "".join(p.capitalize() for p in parts[1:]) + "".join(trailing)
    return out if out[0].isalpha() else "n" + out   # all-numeric name: keep it legal


def field_name(item, sp, parsed):
    """Workbook-authoritative property/parameter base name (Default suffix stripped):
    the clean ada:<name> segment of the `schema path`, else the impl property:/parameter:
    tag name, else camelCase(item). Mirrors the analyteColumn naming so the workbook
    drives names; the camelCase(item) fallback covers rows without schema-path/impl names."""
    if "ada:" in sp and "methodParameters" not in sp and "analyteTemplate" not in sp:
        m = re.search(r"ada:([A-Za-z][A-Za-z0-9]*)", sp)
        if m:
            return re.sub(r"Default$", "", m.group(1))
    for tr in (parsed.get("tag_records") or []):
        if tr["kind"] in ("property", "parameter"):
            return re.sub(r"Default$", "", tr["name"])
    return camel(item)


def jtype(dt):
    d = dt.lower()
    if "integer" in d:
        return "integer"
    if "numeric" in d or "number" in d:
        return "number"
    if "boolean" in d:
        return "boolean"
    if d.startswith("date"):
        return "date"
    if "uri" in d or "doi" in d:
        return "uri"
    return "string"


def unit(dt):
    m = re.search(r"\(([^)]+)\)", dt)
    return m.group(1) if m else None


def meaningful(v):
    v = re.sub(r"\s*\[P[^\]]*\]", "", norm(v)).strip()
    if v in ("", "N", "N/A"):
        return False
    m = re.match(r"^(N/A|N)\b\s*", v)
    if m:
        rest = v[m.end():]
        if rest.startswith("("):
            depth = 0
            for i, ch in enumerate(rest):
                depth += (ch == "(") - (ch == ")")
                if ch == ")" and depth == 0:
                    rest = rest[i + 1:]
                    break
        if re.fullmatch(r"[/;,\-\s]*", rest.strip()):
            return False
    return True


