def build():
    os.makedirs(TAPP_DIR, exist_ok=True)
    os.makedirs(DETAIL_DIR, exist_ok=True)
    R = route()
    for b in R["vocab"]:
        write_vocab(b)

    remove_owned_blocks(PT, PARAM_BASE + "/")
    remove_owned_blocks(PV, PARAM_BASE + "/")
    pt_existing, pv_existing = existing_keys(PT), existing_keys(PV)

    pt_defs, pt_keys = {}, []
    for b in R["method_param"]:
        n, d = param_template_def(b, pt_existing); pt_defs.update(d); pt_keys.append(n); pt_existing.add(n)
    append_defs(PT, pt_defs)

    pv_defs, pv_keys, pv_ids, seen = {}, [], [], set()
    for b in R["detail_addl"]:
        if b["name"] in seen:
            continue
        seen.add(b["name"])
        n, d = param_value_def(b, pv_existing); pv_defs.update(d); pv_keys.append(n)
        pv_ids.append(PARAM_BASE + "/" + b["name"]); pv_existing.add(n)
    # Advanced + Read-Only -> PropertyValue (fixed protocol value) in parameterValues,
    # referenced from the TAPP schema:additionalProperty (alongside the editable specs).
    mv_keys = []
    for b in R["method_value"]:
        if b["name"] in seen:
            continue
        seen.add(b["name"])
        n, d = param_value_def(b, pv_existing); pv_defs.update(d); mv_keys.append(n); pv_existing.add(n)
    append_defs(PV, pv_defs)

    acols = []
    for b in R["analyte_cols"]:
        for c in b["cols"]:
            if c not in acols:
                acols.append(c)
    if R.get("analyte_defs"):
        import _tapp_lib as _L
        _L.TAPP_NAME = TAPP
        _L.write_analyte_columns_registry(R["analyte_defs"])

    # ---- TAPP schema ----
